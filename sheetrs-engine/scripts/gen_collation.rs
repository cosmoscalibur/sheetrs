//! Derives the collation table of sheetrs-engine from ICU/CLDR (root collation).
//! Not part of the workspace: put this file as `src/main.rs` and
//! `gen_collation.Cargo.toml` as `Cargo.toml` in a scratch crate (the workspace's
//! toolchain), run it and write its output to `src/collate/data.rs`.
//!
//! primary / secondary / tertiary classes of the characters in TABLE.
use icu_collator::options::{CollatorOptions, Strength};
use icu_collator::{Collator, CollatorPreferences};
use icu_locale::locale;
use std::cmp::Ordering;

fn coll(s: Strength) -> icu_collator::CollatorBorrowed<'static> {
    let mut o = CollatorOptions::default();
    o.strength = Some(s);
    Collator::try_new(CollatorPreferences::from(locale!("en")), o).unwrap()
}

const CANDIDATES: &[(char, &str)] = &[
    ('\u{bc}', "1⁄4"),
    ('\u{bd}', "1⁄2"),
    ('\u{be}', "3⁄4"),
    ('\u{132}', "IJ"),
    ('\u{133}', "ij"),
    ('\u{13f}', "L·"),
    ('\u{140}', "l·"),
    ('\u{149}', "ʼn"),
    ('\u{1c4}', "DZ"),
    ('\u{1c5}', "Dz"),
    ('\u{1c6}', "dz"),
    ('\u{1c7}', "LJ"),
    ('\u{1c8}', "Lj"),
    ('\u{1c9}', "lj"),
    ('\u{1ca}', "NJ"),
    ('\u{1cb}', "Nj"),
    ('\u{1cc}', "nj"),
    ('\u{1f1}', "DZ"),
    ('\u{1f2}', "Dz"),
    ('\u{1f3}', "dz"),
    ('\u{2025}', ".."),
    ('\u{2026}', "..."),
    ('\u{2033}', "′′"),
    ('\u{2034}', "′′′"),
    ('\u{2036}', "‵‵"),
    ('\u{2037}', "‵‵‵"),
    ('\u{203c}', "!!"),
    ('\u{2047}', "??"),
    ('\u{2048}', "?!"),
    ('\u{2049}', "!?"),
    ('\u{2057}', "′′′′"),
    ('\u{20a8}', "Rs"),
    ('\u{2100}', "a/c"),
    ('\u{2101}', "a/s"),
    ('\u{2103}', "°C"),
    ('\u{2105}', "c/o"),
    ('\u{2106}', "c/u"),
    ('\u{2109}', "°F"),
    ('\u{2116}', "No"),
    ('\u{2120}', "SM"),
    ('\u{2121}', "TEL"),
    ('\u{2122}', "TM"),
    ('\u{213b}', "FAX"),
    ('\u{222c}', "∫∫"),
    ('\u{222d}', "∫∫∫"),
    ('\u{222f}', "∮∮"),
    ('\u{2230}', "∮∮∮"),
];

/// Letter ligatures, whose difference from their letters is a secondary one.
const LIGATURES: &[(char, &str)] = &[('ß', "ss"), ('Æ', "AE"), ('æ', "ae"), ('Œ', "OE"), ('œ', "oe"), ('Ĳ', "IJ"), ('ĳ', "ij")];

fn main() {
    let (p, s, t) = (coll(Strength::Primary), coll(Strength::Secondary), coll(Strength::Tertiary));
    let mut chars: Vec<char> = Vec::new();
    let ranges = [0x09u32..=0x0D, 0x20..=0x7E, 0xA0..=0x24F, 0x2000..=0x206F, 0x20A0..=0x20CF, 0x2100..=0x214F, 0x2190..=0x22FF];
    for cp in ranges.iter().cloned().flatten() {
        if let Some(c) = char::from_u32(cp) { chars.push(c); }
    }
    // Expansions: characters whose primary weights equal those of a string.
    let mut exps: Vec<(char, String, u16, u8)> = Vec::new();
    for &(c, e) in LIGATURES {
        exps.push((c, e.to_string(), 300, if c.is_uppercase() { 2 } else { 1 }));
    }
    for &(c, e) in CANDIDATES {
        if LIGATURES.iter().any(|l| l.0 == c) { continue; }
        let known = e.chars().all(|x| chars.contains(&x));
        if known && p.compare(&c.to_string(), e) == Ordering::Equal {
            exps.push((c, e.to_string(), 0, 1));
        }
    }
    let single = |c: char| !exps.iter().any(|e| e.0 == c) && p.compare(&c.to_string(), "") != Ordering::Equal;
    let mut cs: Vec<char> = chars.iter().copied().filter(|&c| single(c)).collect();
    cs.sort_by(|a, b| p.compare(&a.to_string(), &b.to_string()));
    // primary classes
    let mut prim: Vec<(char, u32)> = Vec::new();
    let mut cls = 0u32;
    for (i, &c) in cs.iter().enumerate() {
        if i > 0 && p.compare(&cs[i - 1].to_string(), &c.to_string()) != Ordering::Equal {
            cls += 1;
        }
        prim.push((c, cls));
    }
    // secondary / tertiary ranks within each primary class
    let mut out: Vec<(char, u32, u32, u32)> = Vec::new();
    let mut i = 0;
    while i < prim.len() {
        let mut j = i;
        while j < prim.len() && prim[j].1 == prim[i].1 { j += 1; }
        let mut grp: Vec<char> = prim[i..j].iter().map(|x| x.0).collect();
        grp.sort_by(|a, b| s.compare(&a.to_string(), &b.to_string()));
        let mut sec = 0u32;
        let mut k = 0;
        while k < grp.len() {
            let mut m = k;
            while m < grp.len() && s.compare(&grp[k].to_string(), &grp[m].to_string()) == Ordering::Equal { m += 1; }
            let mut sub: Vec<char> = grp[k..m].to_vec();
            sub.sort_by(|a, b| t.compare(&a.to_string(), &b.to_string()));
            let mut ter = 0u32;
            for (n, &c) in sub.iter().enumerate() {
                if n > 0 && t.compare(&sub[n - 1].to_string(), &c.to_string()) != Ordering::Equal { ter += 1; }
                out.push((c, prim[i].1, sec, ter));
            }
            sec += 1;
            k = m;
        }
        i = j;
    }
    out.sort();
    println!("// @generated by scripts/gen_collation: root collation (CLDR): whitespace controls, U+0020..U+007E, U+00A0..U+024F, general punctuation, currency, arrows and math.");
    println!("// (char, primary class, secondary rank, tertiary rank); characters that collate as a string are in `EXPANSIONS` (char, string, secondary, tertiary).");
    println!("pub(super) static TABLE: &[(char, u16, u8, u8)] = &[");
    for (c, a, b, d) in &out {
        println!("    ({:?}, {}, {}, {}),", c, a, b, d);
    }
    println!("];");
    // expansions: what the ICU primary weights equal
    println!("pub(super) static EXPANSIONS: &[(char, &str, u16, u8)] = &[");
    for (c, e, sec, t) in &exps {
        println!("    ({:?}, {:?}, {}, {}),", c, e, sec, t);
    }
    println!("];");
    println!("pub(super) static IGNORABLE: &[char] = &[");
    for &c in chars.iter().filter(|&&c| p.compare(&c.to_string(), "") == Ordering::Equal) {
        println!("    {:?},", c);
    }
    println!("];");
    // combining marks
    let mut cm: Vec<char> = (0x300u32..=0x36F).filter_map(char::from_u32).collect();
    cm.sort_by(|a, b| s.compare(&format!("a{a}"), &format!("a{b}")));
    let mut r = 0u8;
    println!("pub(super) static COMBINING: &[(char, u8)] = &[");
    for (n, &c) in cm.iter().enumerate() {
        if n > 0 && s.compare(&format!("a{}", cm[n - 1]), &format!("a{c}")) != Ordering::Equal { r += 1; }
        println!("    ({:?}, {}),", c, r);
    }
    println!("];");
}

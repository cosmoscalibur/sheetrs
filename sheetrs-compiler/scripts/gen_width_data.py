#!/usr/bin/env python3
"""Writes sheetrs-engine/src/functions/width_data.rs: what LibreOffice answers for `LENB` (the
width of every character of the Basic Multilingual Plane), `ASC` and `JIS` (the characters they
change, and the pairs of half-width kana and voiced mark that `JIS` joins).

Usage: SOFFICE=/path/to/soffice scripts/gen_width_data.py   (needs openpyxl)
"""
import os
import subprocess
import sys
import tempfile
import zipfile
from xml.etree import ElementTree as ET

import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "sheetrs-engine", "src", "functions", "width_data.rs")
SOFFICE = os.environ.get("SOFFICE", "soffice")
NS = {"t": "urn:oasis:names:tc:opendocument:xmlns:table:1.0", "o": "urn:oasis:names:tc:opendocument:xmlns:office:1.0"}


def evaluate(formulas):
    """The values LibreOffice computes for the formulas, as strings."""
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "w.xlsx")
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Calc"
        for i, f in enumerate(formulas, start=1):
            ws[f"A{i}"] = "=" + f
        wb.save(src)
        subprocess.run([SOFFICE, "--headless", "--convert-to", "ods", "--outdir", tmp, src], check=True, capture_output=True)
        root = ET.fromstring(zipfile.ZipFile(os.path.join(tmp, "w.ods")).read("content.xml"))
    out = []
    for table in root.iter("{%s}table" % NS["t"]):
        for row in table.iter("{%s}table-row" % NS["t"]):
            rep = int(row.get("{%s}number-rows-repeated" % NS["t"], "1"))
            cells = row.findall("t:table-cell", NS)
            if not cells:
                continue
            c = cells[0]
            vt = c.get("{%s}value-type" % NS["o"])
            v = c.get("{%s}value" % NS["o"]) if vt in ("float", "percentage", "currency") else "".join(c.itertext())
            out.extend([v] * min(rep, 1))
    return out


def chunked(items, size, make):
    for i in range(0, len(items), size):
        part = items[i:i + size]
        yield part, evaluate([make(n) for n in part])


def main():
    bmp = [n for n in range(1, 0x10000) if not 0xD800 <= n <= 0xDFFF]
    width = {}
    for part, vals in chunked(bmp, 16000, lambda n: f"LENB(_xlfn.UNICHAR({n}))"):
        width.update(zip(part, (int(float(v)) for v in vals)))
    ones = [n for n in sorted(width) if width[n] == 1]
    ranges = []
    for n in ones:
        if ranges and n == ranges[-1][1] + 1:
            ranges[-1][1] = n
        else:
            ranges.append([n, n])
    # Surrogates are counted as the pair they make: two for any character above the plane.
    asc, jis = [], []
    probe = list(range(1, 0x2000)) + list(range(0x2000, 0x6000)) + list(range(0xFE00, 0x10000))
    for name, table in (("ASC", asc), ("JIS", jis)):
        for part, vals in chunked(probe, 5000, lambda n: f"LEN({name}(_xlfn.UNICHAR({n})))"):
            lens = dict(zip(part, vals))
            changed = []
            for n in part:
                if 0xD800 <= n <= 0xDFFF:
                    continue
                changed.append(n)
            codes = evaluate([f"_xlfn.UNICODE({name}(_xlfn.UNICHAR({n})))" for n in changed])
            seconds = evaluate([f"IF(LEN({name}(_xlfn.UNICHAR({n})))>1,_xlfn.UNICODE(MID({name}(_xlfn.UNICHAR({n})),2,1)),0)" for n in changed])
            for n, c, s, in zip(changed, codes, seconds):
                c, s = int(float(c)), int(float(s))
                if int(float(lens[n])) == 1 and c == n:
                    continue
                table.append((n, c, s))
    # The pairs JIS joins.
    pairs = []
    marks = [(0xFF9E, "voiced"), (0xFF9F, "semi")]
    bases = list(range(0xFF66, 0xFF9E))
    for mark, _ in marks:
        lens = evaluate([f"LEN(JIS(_xlfn.UNICHAR({b})&_xlfn.UNICHAR({mark})))" for b in bases])
        codes = evaluate([f"_xlfn.UNICODE(JIS(_xlfn.UNICHAR({b})&_xlfn.UNICHAR({mark})))" for b in bases])
        for b, l, c in zip(bases, lens, codes):
            if int(float(l)) == 1:
                pairs.append((b, mark, int(float(c))))
    with open(OUT, "w") as f:
        f.write("//! Generated by `sheetrs-compiler/scripts/gen_width_data.py` from LibreOffice 26.8: the character\n")
        f.write("//! widths of `LENB` and the conversions of `ASC` and `JIS`. Do not edit.\n\n")
        f.write("/// The ranges of the Basic Multilingual Plane that count one byte in `LENB` (the rest, and every\n")
        f.write("/// character above the plane, count two).\n")
        f.write("pub(super) const SINGLE_BYTE: &[(u32, u32)] = &[\n")
        for a, b in ranges:
            f.write(f"    ({a:#06x}, {b:#06x}),\n")
        f.write("];\n\n")
        f.write("/// `ASC`: the characters it changes, to one character or to two (the second is 0 when there is one).\n")
        f.write("pub(super) const ASC: &[(u32, u32, u32)] = &[\n")
        for n, c, s in asc:
            f.write(f"    ({n:#06x}, {c:#06x}, {s:#06x}),\n")
        f.write("];\n\n")
        f.write("/// `JIS`: the same for the full-width forms.\n")
        f.write("pub(super) const JIS: &[(u32, u32, u32)] = &[\n")
        for n, c, s in jis:
            f.write(f"    ({n:#06x}, {c:#06x}, {s:#06x}),\n")
        f.write("];\n\n")
        f.write("/// `JIS`: a half-width kana followed by a voiced or semi-voiced mark, and the character it becomes.\n")
        f.write("pub(super) const JIS_PAIRS: &[(u32, u32, u32)] = &[\n")
        for b, m, c in pairs:
            f.write(f"    ({b:#06x}, {m:#06x}, {c:#06x}),\n")
        f.write("];\n")
    print(f"{len(ranges)} width ranges, {len(asc)} ASC, {len(jis)} JIS, {len(pairs)} pairs -> {OUT}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Which functions keep the boolean format of an argument on a single value in `LibreOffice` 26.8
(`VALUE(TRUE())` is the number 1 that the cell shows as TRUE), and the table the engine takes from it
(`sheetrs-engine/src/functions/keep_format_table.rs`).

    scripts/probe_logical.py ask RAW.json        # asks LibreOffice (needs soffice, openpyxl, cargo)
    scripts/probe_logical.py table RAW.json      # writes keep_format_table.rs from the answers

`LibreOffice` gives a formula cell the number format of what the formula ends with: a function that sets
none leaves the one of the last operand that had it (`VALUE(TRUE())`, `+TRUE()`, `-TRUE()` are shown as
TRUE), a function that sets one gives it (`ABS(TRUE())`, `SUM(TRUE())`, `TRUE()+0` are the number 1).
For every function and every argument position the call is made with `TRUE()` there and a number (or
the other kinds of base the arity probe uses) in the rest, and with numbers only: a position is kept
when the cell with `TRUE()` is a boolean and the cell without it is not (a function that gives a
boolean by itself, `ISNUMBER`, `AND`, is not in the table: the engine already gives a boolean).
"""
import json
import os
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lo_probe  # noqa: E402
import probe_arity as pa  # noqa: E402

ROOT = os.path.join(HERE, "..", "..")
OUT = os.path.join(ROOT, "sheetrs-engine", "src", "functions", "keep_format_table.rs")
RANDOM = {"RAND", "RANDBETWEEN", "RANDARRAY"}
BASES = [
    lambda n: ["2"] * n,
    lambda n: ["1"] * n,
    lambda n: ["3", "2", "1"] + ["1"] * (n - 3) if n >= 3 else ["3"] * n,
    lambda n: ['"abc"'] + ["2"] * (n - 1),
    lambda n: ["0.5"] * n,
]


def ask(out_path):
    funcs = [(ns, name, int(mn), int(mx)) for ns, name, mn, mx in pa.registry()]
    funcs = [f for f in funcs if (f[0], f[1]) not in pa.NOT_PROBED and not f[1].startswith("_") and f[1] not in RANDOM]
    spelling = pa.find_spellings(funcs)
    rows = []
    for ns, name, mn, mx in funcs:
        if (ns, name) not in spelling:
            continue
        prefix, nm = spelling[(ns, name)]
        for n in range(max(mn, 1), min(mx, max(mn, 1) + 2) + 1):
            for base in BASES:
                args = base(n)[:n]
                calls = [f"{prefix}{nm}({','.join(args)})"]
                for p in range(min(n, 6)):
                    a = list(args)
                    a[p] = "TRUE()"
                    calls.append(f"{prefix}{nm}({','.join(a)})")
                rows.append((ns, name, n, calls))
    allf = [f for r in rows for f in r[3]]
    print(len(allf), "formulas", file=sys.stderr)
    chunks = [allf[i : i + 800] for i in range(0, len(allf), 800)]

    def run(chunk):
        try:
            return lo_probe.probe(chunk)
        except Exception:
            res = []
            for f in chunk:
                try:
                    res.append(lo_probe.probe([f])[0])
                except Exception:
                    res.append(("crash", ""))
            return res

    with ThreadPoolExecutor(3) as pool:
        answers = list(pool.map(run, chunks))
    flat = [a for ans in answers for a in ans]
    json.dump({"rows": rows, "answers": flat}, open(out_path, "w"))


def classify(raw):
    """`{(name, ns): mask}`: the argument positions where a `TRUE()` is kept."""
    out = {}
    i = 0
    for ns, name, n, calls in raw["rows"]:
        ans = raw["answers"][i : i + len(calls)]
        i += len(calls)
        base, with_true = ans[0], ans[1:]
        if base[0] == "boolean" or "crash" in [a[0] for a in ans]:
            continue  # a boolean by itself, or LibreOffice failed
        for p, a in enumerate(with_true):
            if a[0] == "boolean" and base[0] != "error":
                out[(name, ns)] = out.get((name, ns), 0) | 1 << p
    return out


def table(raw_path):
    raw = json.load(open(raw_path))
    kept = classify(raw)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("//! The functions that keep the boolean format of an argument on a single value in `LibreOffice`\n")
        f.write("//! 26.8: `VALUE(TRUE())` is the number 1 that its cell shows as TRUE, where `ABS(TRUE())` is the\n")
        f.write("//! number 1.\n//!\n")
        f.write("//! Generated by `sheetrs-compiler/scripts/probe_logical.py`: do not edit.\n\n")
        f.write("/// `(name, namespace, arguments)`, sorted by name and namespace: a bit per argument, the first is bit 0.\n")
        f.write("pub(super) const KEEPS: &[(&str, &str, u32)] = &[\n")
        for (name, ns), mask in sorted(kept.items()):
            f.write(f'    ("{name}", "{ns}", {mask}),\n')
        f.write("];\n")
    print(len(kept), "functions keep the format:", sorted(n for n, _ in kept), file=sys.stderr)


if __name__ == "__main__":
    {"ask": lambda: ask(sys.argv[2]), "table": lambda: table(sys.argv[2])}[sys.argv[1]]()

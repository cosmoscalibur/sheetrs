#!/usr/bin/env python3
"""Maps every function LibreOffice offers to the name its ODS and XLSX files give it.

Each function of the catalogue (UNO `FunctionDescriptions`) is written as a formula in a
document that is saved as ODS and as XLSX; the tokens of both files are paired. Prints a
JSON object {catalogue name: {"ods": ..., "xlsx": ...}}.

With a second argument it also writes the report as Markdown (docs/FUNCTION_NAMES.md), and
with a third the Rust table the engine registers its functions by
(sheetrs-engine/src/functions/namespaces.rs).

Run with LibreOffice's Python:
  SOFFICE=soffice26 .../program/python scripts/function_namespaces.py OUT.json [OUT.md [OUT.rs]]
"""
import html
import json
import os
import re
import subprocess
import sys
import tempfile
import time
import zipfile

import uno
from com.sun.star.beans import PropertyValue

SOFFICE = os.environ.get("SOFFICE", "soffice")
OUT = sys.argv[1] if len(sys.argv) > 1 else "namespaces.json"
PORT = 2012


def pv(n, v):
    p = PropertyValue(); p.Name, p.Value = n, v; return p


def main():
    profile = tempfile.mkdtemp(prefix="lo_ns_")
    proc = subprocess.Popen([SOFFICE, "--headless", "--invisible", "--norestore", f"-env:UserInstallation=file://{profile}",
                             f"--accept=socket,host=localhost,port={PORT};urp;"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    local = uno.getComponentContext()
    ctx = None
    for _ in range(90):
        try:
            r = local.ServiceManager.createInstanceWithContext("com.sun.star.bridge.UnoUrlResolver", local)
            ctx = r.resolve(f"uno:socket,host=localhost,port={PORT};urp;StarOffice.ComponentContext"); break
        except Exception:
            time.sleep(1)
    smgr = ctx.ServiceManager
    desktop = smgr.createInstanceWithContext("com.sun.star.frame.Desktop", ctx)
    fd = smgr.createInstanceWithContext("com.sun.star.sheet.FunctionDescriptions", ctx)
    names = []
    for i in range(fd.Count):
        props = {x.Name: x.Value for x in fd.getByIndex(i)}
        names.append(props["Name"])
    doc = desktop.loadComponentFromURL("private:factory/scalc", "_blank", 0, (pv("Hidden", True),))
    sh = doc.Sheets.getByIndex(0)
    for i, n in enumerate(names):
        sh.getCellByPosition(0, i).setFormula(f"={n}(1;1)")
    tmp = tempfile.mkdtemp(prefix="lo_ns_out_")
    for ext, flt in (("ods", "calc8"), ("xlsx", "Calc MS Excel 2007 XML")):
        doc.storeToURL(uno.systemPathToFileUrl(os.path.join(tmp, "f." + ext)), (pv("FilterName", flt),))
    doc.close(True)
    try:
        desktop.terminate()
    except Exception:
        pass
    proc.wait(timeout=60)
    ods = re.findall(r'table:formula="([^"]*)"', zipfile.ZipFile(os.path.join(tmp, "f.ods")).read("content.xml").decode())
    xml = zipfile.ZipFile(os.path.join(tmp, "f.xlsx")).read("xl/worksheets/sheet1.xml").decode()
    xlsx = [html.unescape(m) for m in re.findall(r"<f[^>]*>([^<]*)</f>", xml)]
    tok = lambda s: re.match(r"=?(?:of:=)?\s*=?([A-Za-z0-9_.]+)\(", html.unescape(s))
    out = {}
    for n, o, x in zip(names, ods, xlsx):
        mo, mx = tok(o), tok(x)
        out[n] = {"ods": mo.group(1) if mo else o, "xlsx": mx.group(1) if mx else x}
    json.dump(out, open(OUT, "w"), indent=1)
    if len(sys.argv) > 2:
        open(sys.argv[2], "w").write(markdown(out))
    if len(sys.argv) > 3:
        open(sys.argv[3], "w").write(rust_table(out))
    print(len(names), len(ods), len(xlsx))


NS = ("COM.MICROSOFT.", "ORG.OPENOFFICE.", "ORG.LIBREOFFICE.", "LEGACY.")
RUST_NS = {"COM.MICROSOFT.": "Microsoft", "ORG.OPENOFFICE.": "OpenOffice", "ORG.LIBREOFFICE.": "LibreOffice", "LEGACY.": "Legacy"}


def rust_table(out):
    """The namespace of every function outside `core` (the ODF standard, no prefix)."""
    internal = lambda n: n.endswith(("_ADD", "_EXCEL2003"))
    outside, bare_in_xlsx, core = {}, {}, set()
    for n, v in out.items():
        if internal(n):
            continue
        o, x = v["ods"], v["xlsx"]
        prefix = next((p for p in NS if o.startswith(p)), None)
        if prefix is None:
            core.add(o)
            continue
        name = o[len(prefix):]
        outside[name] = RUST_NS[prefix]
        if not x.startswith("_xl"):
            bare_in_xlsx[name] = RUST_NS[prefix]
    clash = sorted(set(outside) & core)
    for n in clash:
        del outside[n]
    lines = ["//! Generated by `sheetrs-compiler/scripts/function_namespaces.py` from the function catalogue of",
             "//! LibreOffice 26.8: do not edit. A function is in a namespace by the prefix its ODS name carries.",
             "", "use crate::ir::Ns;", "",
             "/// Functions outside `core` (the ODF standard, whose names carry no prefix), by the bare name that",
             "/// ODS and XLSX share. A name that is also a core function (`" + "`, `".join(clash) + "`) is",
             "/// registered by hand in both namespaces.",
             "pub(super) static OUTSIDE_CORE: &[(&str, Ns)] = &["]
    lines += [f'    ("{n}", Ns::{ns}),' for n, ns in sorted(outside.items())]
    lines += ["];", "",
              "/// Names an XLSX writes without `_xlfn.` for a function that is not in `core`: they mean the function of",
              "/// that namespace there, and the core one of the same text in an ODS.",
              "pub static XLSX_BARE: &[(&str, Ns)] = &["]
    lines += [f'    ("{n}", Ns::{ns}),' for n, ns in sorted(bare_in_xlsx.items())]
    lines += ["];", ""]
    # Every function LibreOffice has, by the names a formula writes it with (prefixes dropped): the
    # inventory a build checks the formulas against.
    names = set()
    for n, v in out.items():
        if internal(n):
            continue
        o = v["ods"]
        o = o.rsplit(".", 1)[-1] if o.startswith("COM.SUN") else next((o[len(p):] for p in NS if o.startswith(p)), o)
        x = v["xlsx"]
        for p in ("_xlfn.", "_xlws."):
            x = x[len(p):] if x.startswith(p) else x
        x = next((x[len(p):] for p in NS if x.startswith(p)), x)
        names |= {o.upper(), x.upper()}
    lines += ["/// Every function of LibreOffice's catalogue, by the name a formula writes it with, uppercase and",
              "/// without prefix. A function here that the engine does not implement stops the build; a name that",
              "/// is not here is unknown to LibreOffice too (`#NAME?`).",
              "pub static CATALOGUE: &[&str] = &["]
    lines += [f'    "{n}",' for n in sorted(names)]
    lines += ["];", ""]
    return "\n".join(lines)


def markdown(out):
    # `NAME_ADD` / `NAME_EXCEL2003` are internal duplicates of a function that serialize to the same text.
    internal = lambda n: n.endswith(("_ADD", "_EXCEL2003"))
    ods_names = {v["ods"]: n for n, v in out.items() if not internal(n)}
    strip = lambda t: t.replace("_xlfn.", "").replace("_xlws.", "")
    bare = lambda t: next((t[len(p):] for p in NS if t.startswith(p)), t)
    plain = [n for n, v in out.items() if v["ods"] == v["xlsx"] and not v["ods"].startswith("COM.SUN")]
    prefixed = [n for n, v in out.items() if v["ods"].startswith(NS[:3]) and v["xlsx"].startswith("_xlfn.") and strip(v["xlsx"]) == bare(v["ods"]).replace("COM.MICROSOFT.", "")]
    lo_only = [(n, v) for n, v in out.items() if v["ods"].startswith(("ORG.OPENOFFICE.", "ORG.LIBREOFFICE."))]
    addins = [(n, v) for n, v in out.items() if v["ods"].startswith("COM.SUN")]
    legacy = [(n, v) for n, v in out.items() if v["ods"].startswith("LEGACY.")]
    renamed = [(n, v) for n, v in out.items() if strip(v["xlsx"]) != bare(v["ods"]) and not v["ods"].startswith(("COM.SUN", "ORG.", "LEGACY."))]
    clash = []
    for n, v in out.items():
        if internal(n):
            continue
        for t in (v["xlsx"], strip(v["xlsx"])):
            if t in ods_names and ods_names[t] != n:
                clash.append((t, n, ods_names[t]))
    counts = {}
    for n, v in out.items():
        if internal(n):
            continue
        o = v["ods"]
        key = "COM.SUN" if o.startswith("COM.SUN") else next((p for p in NS if o.startswith(p)), "")
        counts[key] = counts.get(key, 0) + 1
    lines = ["# Function names by file format (LibreOffice 26.8)", "",
             "Generated by `scripts/function_namespaces.py`: every function of LibreOffice's catalogue is written to an ODS and to an XLSX",
             "and the name each file gives it is paired. A function belongs to a **namespace**, which OpenDocument writes as a prefix; the",
             "same text can name two functions in two namespaces, and the engine registers them as `namespace::NAME`.", "",
             "| Namespace | Prefix in an ODS | In an XLSX | Functions | What it holds |", "| --- | --- | --- | --: | --- |",
             f"| `core` | none | the bare name | {counts.get('', 0)} | The OpenDocument standard (OpenFormula): `SUM`, `IF`, `VLOOKUP`, `CEILING`… |",
             f"| `microsoft` | `COM.MICROSOFT.` | `_xlfn.` (bare for `CEILING`, `FLOOR`, `ISO.CEILING`, `NETWORKDAYS.INTL`, `WORKDAY.INTL`) | {counts.get('COM.MICROSOFT.', 0)} | What Microsoft defined after ODF 1.2 (`IFS`, `XLOOKUP`, `STDEV.S`…) and Excel's version of a function whose bare name is something else (`CEILING`, `FLOOR`) |",
             f"| `libreoffice` | `ORG.LIBREOFFICE.` | `_xlfn.ORG.LIBREOFFICE.` | {counts.get('ORG.LIBREOFFICE.', 0)} | LibreOffice's own extensions (`REGEX`, `COLOR`, `ROUNDSIG`, `FOURIER`…) |",
             f"| `openoffice` | `ORG.OPENOFFICE.` | `_xlfn.ORG.OPENOFFICE.` or bare (`WEEKS`, `MONTHS`, `ROT13`…) | {counts.get('ORG.OPENOFFICE.', 0)} | Extensions that come from OpenOffice (`ERRORTYPE`, `CONVERT`, `DAYSINMONTH`…) |",
             f"| `legacy` | `LEGACY.` | the bare name | {counts.get('LEGACY.', 0)} | The pre-ODF-1.2 function whose bare name now means another (`FDIST`, `TDIST`, `NORMSDIST`…) |",
             f"| add-ins | `COM.SUN.STAR.SHEET.ADDIN.…` | the bare name | {counts.get('COM.SUN', 0)} | Functions the analysis add-in implements; for the engine they are `core` |", "",
             f"* {len(plain)} functions have the same name in both formats (`SUM`, `IF`, `VLOOKUP`…).",
             f"* {len(prefixed)} functions of the 2010+ generation are `_xlfn.NAME` in XLSX and `COM.MICROSOFT.NAME` (or `ORG.OPENOFFICE.`/`ORG.LIBREOFFICE.`) in ODS.",
             f"* {len(addins)} are add-in functions in ODS, plain in XLSX; {len(legacy)} are `LEGACY.NAME` in ODS and `NAME` in XLSX.",
             "* `EASTERSUNDAY` is bare in an ODS and `_xlfn.ORG.OPENOFFICE.EASTERSUNDAY` in an XLSX: the two formats disagree on its namespace.", "",
             "## Same text, different function", "",
             "| Text | In an XLSX it is | In an ODS it is |", "| --- | --- | --- |"]
    seen = set()
    for t, n, m in clash:
        if t in seen:
            continue
        seen.add(t)
        xl_ns = next((r for p, r in RUST_NS.items() if out[n]["ods"].startswith(p)), "core")
        od_ns = next((r for p, r in RUST_NS.items() if out[m]["ods"].startswith(p)), "core")
        lines.append(f"| `{t}` | `{xl_ns.lower()}::{t}` | `{od_ns.lower()}::{t}` |")
    lines += ["", "A bare `CEILING`/`FLOOR` in an ODS is the OpenDocument function, `core::CEILING` (the signs of number and multiple must agree; its XLSX",
              "export is `CEILING.MATH`/`FLOOR.MATH`, which it is not); Excel's `CEILING`/`FLOOR` are `microsoft::CEILING`/`FLOOR` (`COM.MICROSOFT.CEILING` in an ODS, bare in an XLSX).",
              "`FDIST`/`FINV` in an ODS are the ODF functions (`F.DIST`/`F.INV`'s generation); the legacy ones are `LEGACY.FDIST`/`LEGACY.FINV`.", "",
              "## Renamed (the name differs beyond the prefix)", "", "| LibreOffice | ODS | XLSX |", "| --- | --- | --- |"]
    for n, v in renamed:
        lines.append(f"| `{n}` | `{v['ods']}` | `{v['xlsx']}` |")
    lines += ["", "## Functions without an Excel counterpart (LibreOffice only)", "", "| Function | ODS | XLSX export |", "| --- | --- | --- |"]
    for n, v in lo_only:
        lines.append(f"| `{n}` | `{v['ods']}` | `{v['xlsx']}` |")
    lines += ["", "## Legacy names (`LEGACY.` in ODS)", "", "| Function | ODS | XLSX |", "| --- | --- | --- |"]
    for n, v in legacy:
        lines.append(f"| `{n}` | `{v['ods']}` | `{v['xlsx']}` |")
    lines += ["", "## Add-in functions", "", "| Function | ODS |", "| --- | --- |"]
    for n, v in addins:
        lines.append(f"| `{n}` | `{v['ods']}` |")
    return "\n".join(lines) + "\n"


main()
